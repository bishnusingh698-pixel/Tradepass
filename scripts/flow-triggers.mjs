// Writes extensions/tradepass-flow-<trigger>/shopify.extension.toml from TRIGGER_FIELDS in
// app/lib/flow.server.ts (tests/automation-flow.test.ts checks they match). Run after changing fields:
//   node scripts/flow-triggers.mjs
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";

const src = readFileSync("app/lib/flow.server.ts", "utf8");
const block = (name) => src.slice(src.indexOf(`export const ${name}`), src.indexOf("};", src.indexOf(`export const ${name}`)) + 2);
const app = /const APPLICATION_FIELDS: FieldKey\[\] = \[([^\]]*)\]/.exec(src)[1].match(/"[^"]+"/g).map((x) => JSON.parse(x));
const fields = {};
for (const m of block("TRIGGER_FIELDS").matchAll(/(\w+): (APPLICATION_FIELDS|\[([^\]]*)\])/g)) {
  const list = m[2] === "APPLICATION_FIELDS" ? app : [...m[3].matchAll(/"[^"]+"|\.\.\.APPLICATION_FIELDS/g)].flatMap((x) => (x[0] === "...APPLICATION_FIELDS" ? app : [JSON.parse(x[0])]));
  fields[m[1]] = list;
}
const types = Object.fromEntries([...block("FIELD_TYPES").matchAll(/(?:"([^"]+)"|(\w+)): "([a-z_]+)"/g)].map((m) => [m[1] ?? m[2], m[3]]));
const META = {
  application_submitted: ["Wholesale application submitted", "Runs when someone submits a Tradepass wholesale application."],
  application_approved: ["Wholesale application approved", "Runs when a Tradepass wholesale application is approved and the buyer's company is set up."],
  application_rejected: ["Wholesale application rejected", "Runs when a Tradepass wholesale application is rejected."],
  application_info_received: ["Wholesale application info received", "Runs when an applicant sends the information you asked for with Ask for more info."],
  certificate_expiring: ["Certificate expiring", "Runs when a wholesale buyer's tax or resale certificate will expire soon."],
  certificate_expired: ["Certificate expired", "Runs when a wholesale buyer's tax or resale certificate has expired."],
};
for (const [trigger, list] of Object.entries(fields)) {
  const handle = `tradepass-flow-${trigger.replace(/_/g, "-")}`;
  const [name, description] = META[trigger];
  const body = list.map((k) => (types[k] === "company_reference" ? `  [[settings.fields]]\n  type = "company_reference"\n` : `  [[settings.fields]]\n  type = "${types[k]}"\n  key = "${k}"\n`)).join("\n");
  mkdirSync(`extensions/${handle}`, { recursive: true });
  writeFileSync(`extensions/${handle}/shopify.extension.toml`, `# Shopify Flow trigger fired by app/lib/flow.server.ts (emitFlowTrigger). GENERATED by
# scripts/flow-triggers.mjs from TRIGGER_FIELDS (checked by tests/automation-flow.test.ts).
[[extensions]]
name = "${name}"
type = "flow_trigger"
handle = "${handle}"
description = "${description}"

[settings]

${body}`);
  console.log(handle, list.length, "fields");
}
